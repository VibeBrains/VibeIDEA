package com.vibe.agent.settings

import kotlin.test.Test
import kotlin.test.assertTrue

/**
 * Подсказка на странице настроек обязана ПЕРЕНОСИТЬСЯ по ширине, а не просить её всю в одну строку.
 *
 * Тест меряет результат, а не форму вызова, и в этом вся его суть. Прежний гейт требовал вызова
 * `SettingsUi.hint(`, был зелёным на всех страницах — и страницы всё равно обрезались по правому
 * краю (владелец, 19.09.2026, шесть вкладок подряд). Проверка формы не ловит дефект, потому что
 * форма правильная, а поведение нет.
 *
 * Меряется ровно то, на что жалуется глаз: компоненту дают ширину окна, и он не должен требовать
 * больше. Требует больше — на странице без горизонтальной полосы (мы её выключили) текст просто
 * обрежется, молча.
 */
class SettingsHintWidthTest {
  /** Потолок предпочтительной ширины. Сломанная версия просила 1702 точки при окне в 420. */
  private val CEILING = 900

  private val long = "Тонкие скроллы во всей IDE — дерево проекта, редактор, наши панели и " +
                     "всплывающие списки. Штатные скроллы платформы остаются там, где их рисует " +
                     "сама платформа, и это намеренно: спорить с ней в каждом её окне дороже, чем " +
                     "принять её вид в её же местах."

  /**
   * Главная проверка: подсказка просит РАЗУМНУЮ ширину, а не ширину всей фразы в строку.
   *
   * Именно этим числом дефект и меряется. На сломанной версии подсказка просила 1702 точки —
   * страница брала эту ширину как нужную, растягивалась, и текст уезжал за правый край. Потолок
   * взят с запасом к ширине переноса: важно не точное число, а порядок величины.
   */
  @Test
  fun `подсказка просит ширину порядка строки, а не всей фразы`() {
    val asked = SettingsUi.hint(long).preferredSize.width
    assertTrue(asked in 1..CEILING,
               "подсказка просит $asked точек при потолке $CEILING — столько просит текст в одну строку")
  }

  /**
   * Подсказка занимает НЕСКОЛЬКО строк — то есть перенос действительно случился.
   *
   * Отдельной проверкой «сузили окно — стало выше» здесь не пользуемся, и это осознанно: перенос
   * идёт по фиксированной колонке, как у подсказок самой платформы, и за шириной окна он не
   * следует. Цель правила — чтобы страница не ехала вбок, а не чтобы текст перетекал при каждом
   * движении рамки.
   */
  @Test
  fun `длинная подсказка занимает несколько строк`() {
    val oneLine = SettingsUi.hint("Одна строка").preferredSize.height
    val wrapped = SettingsUi.hint(long).preferredSize.height
    assertTrue(wrapped >= oneLine * 2,
               "длинная подсказка уместилась в $wrapped точек при одной строке в $oneLine — переноса нет")
  }

  /**
   * Высота есть СРАЗУ, до того как компоненту выдали ширину.
   *
   * Это регрессия, которую я внёс сам и которую владелец увидел на 0.6.15: подсказка считала высоту
   * по фактической ширине, а раскладка спрашивает предпочтительный размер ДО того, как выдаст
   * ширину. Ответ «ноль» означает «места не нужно» — и второго вопроса не будет: подсказки пропали
   * со страниц совсем. Проверять надо именно нетронутый компонент, без единого `setSize`.
   */
  @Test
  fun `у нетронутой подсказки высота уже не нулевая`() {
    val hint = SettingsUi.hint(long)
    assertTrue(hint.preferredSize.height > 0,
               "нулевая высота на первом же вопросе означает, что подсказку вовсе не покажут")
  }

  /** Короткая подсказка — одна строка; длинная — несколько. Иначе переноса нет, а есть обрезание. */
  @Test
  fun `длинный текст занимает больше строк, чем короткий`() {
    val short = SettingsUi.hint("Короткая подсказка").preferredSize.height
    val tall = SettingsUi.hint(long).preferredSize.height
    assertTrue(tall > short, "длинная подсказка не стала выше короткой ($tall против $short)")
  }

  @Test
  fun `минимум нулевой — иначе окно не сожмётся ниже него`() {
    assertTrue(SettingsUi.hint(long).minimumSize.width == 0)
  }

  /**
   * Подсказка переносится по ВЫДАННОЙ ширине, а не по своей любимой.
   *
   * Тот самый замер, которого не хватало. Ширина переноса была зашита числом (семьдесят символов),
   * и подсказка сама назначала себе ширину: при крупном шрифте или узком окне её строки шире
   * выданного места, и текст обрезается по правому краю. Прежние проверки этого не видели, потому
   * что мерили подсказку в одиночку — а в одиночку она всегда права.
   *
   * Владелец присылал этот срез четырежды. Здесь он меряется числом: дали 400 — попросила не
   * больше 400.
   */
  @Test
  fun `подсказка переносится по выданной ширине, а не по своей`() {
    val hint = SettingsUi.hint(long)
    for (given in listOf(400, 520, 700)) {
      hint.setBounds(0, 0, given, 1000)
      val asked = hint.preferredSize.width
      assertTrue(asked <= given,
                 "дали $given точек, подсказка просит $asked — на странице её обрежет по правому краю")
    }
  }
}
