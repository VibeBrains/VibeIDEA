package com.vibe.agent.appearance

/**
 * Пара «день/ночь» из коробки — наша, но ровно один раз.
 *
 * Продукт везёт восемь своих тем и до 20.09.2026 предлагал в паре чужие: на снимке владельца с
 * 0.6.17 стояло «Днём: IntelliJ, Ночью: Darcula». Это не выбор человека, а умолчание платформы,
 * доставшееся нам по наследству, — и выглядит оно как недоделанный продукт.
 *
 * Тонкость та же, что у плотности интерфейса ([CompactModeDefault]): «умолчание» и «настройка» —
 * разные вещи. Засев происходит один раз на профиль настроек и только на ЧИСТОЙ паре: стоит
 * человеку задать хотя бы одну половину, спорить с ним мы не имеем права. Засев не меняет текущую
 * тему — он заполняет пару, которой пользуются автодетект и кнопка «Переключить сейчас».
 *
 * Чистая: состояние внутрь, решение наружу.
 */
object ThemePairDefault {
  /** Дневная половина пары — единственная светлая тема набора. */
  const val LIGHT_ID: String = "VibePorcelain"

  /** Ночная половина — наша подпись. */
  const val DARK_ID: String = "VibeNeonDark"

  /** Что делать с парой «день/ночь». */
  enum class Action {
    /** Заполнить обе половины нашими темами и запомнить, что умолчание применено. */
    SEED,

    /** Ничего: либо уже приходили, либо человек сам что-то выбрал. */
    LEAVE_ALONE,
  }

  /**
   * @param alreadySeeded приходили ли мы на этот профиль настроек раньше
   * @param lightSet задана ли дневная половина пары
   * @param darkSet задана ли ночная половина
   */
  fun decide(alreadySeeded: Boolean, lightSet: Boolean, darkSet: Boolean): Action = when {
    alreadySeeded -> Action.LEAVE_ALONE
    // Хватает одной заданной половины: человек уже занимался этой настройкой, и дописывать вторую
    // за него — то же самое, что решать за него целиком.
    lightSet || darkSet -> Action.LEAVE_ALONE
    else -> Action.SEED
  }
}
