package com.vibe.agent.appearance

/**
 * Плотный интерфейс — наше умолчание, но ровно один раз.
 *
 * Решение владельца 05.09.2026: верхняя полоса и заголовки панелей должны быть тоньше, как в
 * PhpStorm; в платформе для этого есть штатный Compact Mode, и трогать `MainToolbar` ради того же
 * результата значит платить merge-налог за то, что уже есть.
 *
 * Тонкость в том, что «умолчание» и «настройка» — разные вещи. Выключить наш плотный режим человек
 * должен уметь навсегда, а не до следующего запуска, поэтому включение происходит **однократно**:
 * в первый раз, когда наша сборка увидела этот профиль настроек. Дальше решает пользователь, и
 * повторное включение было бы не умолчанием, а спором с ним.
 *
 * Чистая: состояние внутрь, решение наружу.
 */
object CompactModeDefault {
  /** Что делать со штатной настройкой плотности. */
  enum class Action {
    /** Включить плотный режим и запомнить, что умолчание применено. */
    ENABLE,
    /** Ничего: либо уже применяли, либо человек уже сам выбрал плотность. */
    LEAVE_ALONE,
  }

  /**
   * @param alreadyApplied применяли ли мы умолчание на этом профиле настроек раньше
   * @param compactAlready включён ли плотный режим прямо сейчас
   */
  fun decide(alreadyApplied: Boolean, compactAlready: Boolean): Action = when {
    alreadyApplied -> Action.LEAVE_ALONE
    compactAlready -> Action.LEAVE_ALONE
    else -> Action.ENABLE
  }
}
