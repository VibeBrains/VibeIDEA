package com.vibe.agent.settings

import com.intellij.openapi.ui.ComboBox
import com.intellij.ui.JBColor
import com.intellij.util.ui.JBUI
import java.awt.Dimension
import javax.swing.JComponent
import javax.swing.JScrollPane
import javax.swing.ScrollPaneConstants

/**
 * Две формы, из которых собирается любая наша страница настроек: сама страница и подсказка на ней.
 *
 * Дефект «страница едет вбок» возвращался четырежды, и каждый раз чинился по-своему, потому что
 * причин у него ДВЕ, а лечили одну.
 *
 * Первая — прокрутка. Оборачивание в [TracksViewportWidthPanel] заставляет вид следовать ширине
 * окна, но только до МИНИМАЛЬНОЙ ширины содержимого: `JViewport` ниже минимума не сжимает. Поэтому
 * минимум панели объявлен нулевым, а горизонтальная полоса выключена совсем — странице настроек
 * ездить вбок незачем ни при каких обстоятельствах.
 *
 * Вторая — сама подсказка. `JBLabel("<html>…")` сообщает ширину В ОДНУ СТРОКУ: страница из-за одной
 * длинной фразы просит ширину в полторы тысячи точек, и всё остальное на ней разъезжается следом.
 * Это ровно то, что владелец увидел на странице языковых серверов 18.09.2026 — подписи ушли за левый
 * край. Копируемый `JBLabel` внутри устроен как текстовая панель: переносит по ширине и честно
 * сообщает высоту после переноса, а заодно позволяет выделить текст подсказки.
 *
 * Правило проекта поэтому спрашивается с одной строки: страница — [page], подсказка — [hint].
 * Проверяет `checkVibeUi.sh`.
 */
object SettingsUi {
  /** Содержимое страницы настроек: вертикальная прокрутка и никакой горизонтальной. */
  fun page(content: JComponent): JScrollPane =
    com.vibe.agent.ui.VibeScroll.pane(TracksViewportWidthPanel(content)).apply {
      horizontalScrollBarPolicy = ScrollPaneConstants.HORIZONTAL_SCROLLBAR_NEVER
      verticalScrollBarPolicy = ScrollPaneConstants.VERTICAL_SCROLLBAR_AS_NEEDED
      border = JBUI.Borders.empty()
    }

  /** Заголовок раздела страницы: то же правило переноса, только полужирным и с отступом сверху. */
  fun section(text: String): JComponent = hint("<b>$text</b>").apply {
    foreground = JBColor.foreground()
    border = JBUI.Borders.emptyTop(8)
  }

  /**
   * Выпадающий список на странице настроек — сжимаемый.
   *
   * Третья причина дефекта «страница едет вбок», и самая упрямая из трёх. Замер 20.09.2026:
   * у `ComboBox` **минимальная ширина равна предпочтительной**, а та растёт с длиной самого
   * длинного пункта. Один такой список поднимает минимум ВСЕЙ формы до своего: форма из двух
   * строк с полями просила минимум 287 точек, та же форма с одним списком — 406, ровно столько
   * же, сколько её предпочтительная. Сжиматься ей больше нечем.
   *
   * Дальше работает то, что мы сами и завели: горизонтальной полосы у страницы нет, поэтому всё
   * правее этого пола не прокручивается, а ОБРЕЗАЕТСЯ. Владелец видел это на странице языковых
   * серверов: поля уехали за правый край, а кнопки диалога налезли друг на друга.
   *
   * Здесь минимум объявлен своим: список ужимается вместе со страницей, длинный пункт в нём
   * показывается многоточием, а выпадающий по щелчку остаётся полной ширины — читать пункты он
   * не мешает.
   */
  fun <T> combo(items: Array<T>): ComboBox<T> = ComboBox(items).apply {
    // Шага здесь ДВА, и одного мало — проверено замером.
    //
    // Первый: у платформенного `ComboBox` минимум по умолчанию равен предпочтительной ширине
    // (`getMinimumSize` объявлен `final` и спрашивает этот флаг). Снимаем флаг.
    //
    // Второй: без него минимум приходит от `JComboBox`, а тот берёт его у своего UI — и `Basic`
    // отдаёт ровно размер самого длинного пункта. То есть список всё равно не сжимается. Поэтому
    // минимальная ширина назначается явно; высота берётся предпочтительная, чтобы список не
    // сплющило по вертикали.
    isUsePreferredSizeAsMinimum = false
    minimumSize = Dimension(JBUI.scale(COMBO_MIN_WIDTH), preferredSize.height)
  }

  /** Ниже этого списку нечего показывать даже многоточием. */
  const val COMBO_MIN_WIDTH: Int = 96

  /**
   * Длинное объяснение под настройкой.
   *
   * [text] — как он лежит в каталоге строк, без обрамляющего `<html>`: тег добавляется здесь, иначе
   * о нём забывают ровно в той строке, которая потом и ломает страницу.
   */
  fun hint(text: String): JComponent = WrappingHint("<html>$text</html>")
}
