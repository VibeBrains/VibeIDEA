#!/usr/bin/env bash
# Правило «упаковочный потомок тега» для релиза, который собирают на нескольких машинах.
#
# Релиз одной версии выходит по одной сборке на ОС, и первая из них ставит тег. Вторая ОС нередко
# требует правок, которых первая не требовала, — иконка лаунчера, картинки инсталлятора, скрипты
# гейтов под другую оболочку. Переставлять опубликованный тег нельзя: то, что уже скачали по нему,
# перестанет совпадать с ним. Собирать со стоковыми чужими картинками — тоже нельзя.
#
# Допустимый выход один и проверяемый: сборка на ПОТОМКЕ тега, чья разница с тегом целиком лежит в
# упаковке и документации — ниже перечислено, что этим считается. Любой файл вне списка означает,
# что продукт изменился, и тогда это уже следующая версия, а не второй артефакт этой.
#
# Использование: releasePackagingOnly.sh vX.Y.Z <коммит>   (код 0 — правило выполнено)
set -euo pipefail
cd "$(dirname "$0")/../.."

VERSION="${1:-}"; COMMIT="${2:-}"
[ -n "$VERSION" ] && [ -n "$COMMIT" ] || { echo "✖ использование: releasePackagingOnly.sh vX.Y.Z <коммит>"; exit 1; }
TAG_COMMIT=$(git rev-parse "$VERSION^{commit}")

git merge-base --is-ancestor "$TAG_COMMIT" "$COMMIT" || {
  echo "✖ $COMMIT не потомок тега $VERSION ($TAG_COMMIT)"; exit 1; }

# Что считается упаковкой: скрипты сборки продукта, ресурсы дистрибутива, инструменты и документы.
# Код плагинов, платформа, сиды — продукт, и их здесь нет намеренно. Скрипт загрузки набора
# серверов допускается, но только без смены закреплённых версий и хешей (проверка ниже): как он
# распаковывает архив — упаковка, какую версию сервера везёт — продукт.
ALLOWED='^(build/|vibeidea-customization/|vibe-plugins/tools/|vibe-plugins/deps/download\.sh$|docs/|[^/]+\.md$)'
CHANGED=$(git diff --name-only "$TAG_COMMIT" "$COMMIT")
OUTSIDE=$(printf '%s\n' "$CHANGED" | grep -Ev "$ALLOWED" || true)
if [ -n "$OUTSIDE" ]; then
  echo "✖ разница с тегом $VERSION выходит за пределы упаковки — это другой продукт, не второй артефакт:"
  printf '%s\n' "$OUTSIDE" | sed 's/^/    /'
  exit 1
fi
PINS=$(git diff "$TAG_COMMIT" "$COMMIT" -- vibe-plugins/deps/download.sh | grep -E '^[-+][^-+]' | grep -E '(_V|SHA)=' || true)
if [ -n "$PINS" ]; then
  echo "✖ в download.sh изменены закреплённые версии или хеши — это другой набор серверов, не второй артефакт:"
  printf '%s\n' "$PINS" | sed 's/^/    /'
  exit 1
fi
echo "  сборка на упаковочном потомке тега $VERSION: разница только в упаковке и документации"
printf '%s\n' "$CHANGED" | sed 's/^/    /'
