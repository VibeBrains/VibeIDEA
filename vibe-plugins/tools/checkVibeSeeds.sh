#!/usr/bin/env bash
# Седьмой гейт: смоук по общему набору `.vibe` — навыки, пайплайны, храповик эвалов.
#
# Шесть прежних гейтов сторожат наш КОД и документацию. Правка поведения агента — навык, пайплайн,
# промпт, правило — не была заперта ничем: набор закрывала только сверка «файл на месте» (манифест
# против ресурсов), то есть ответ «навык существует», а не «навык остался рабочим».
#
# Цена известна цифрами: в отчёте Harness за 2026 год 74 % уверены, что их проверки поймают отказ, а
# автоматический блокирующий гейт есть у 19 %. Мы были во второй группе ровно по этому классу
# изменений.
#
# Проверки живут тестом, а не этим скриптом, и зовут ТОТ ЖЕ код, которым набор читает продукт:
# `SkillValidator` для навыков и `PipelinesFile.load` для пайплайнов. Своя проверка здесь была бы
# второй правдой — она разошлась бы с загрузчиком на первом же новом поле, и разошлась бы молча.
set -euo pipefail
cd "$(dirname "$0")/../.."
. vibe-plugins/tools/bazelTest.sh

TARGET=//vibe-plugins/vibe-agent:vibe-agent_test
FILTER='com.vibe.agent.defaults.SeedsSmokeTest'

bazel_test_verdict "$TARGET" "$FILTER"
printf '%s\n' "$BAZEL_TEST_OUT" | grep -E "Test cases:" || true

case "$BAZEL_TEST_VERDICT" in
  pass)
    echo "Гейт сидов: навыки проходят валидатор, пайплайны читаются загрузчиком, храповик эвалов держит" ;;
  fail)
    printf '%s\n' "$BAZEL_TEST_OUT" | grep -E "FAILED|навык|пайплайн|эвал" | head -20 || true
    echo "Гейт сидов: ПРОВАЛЕН"
    exit 1 ;;
  *)
    echo "ОШИБКА: смоук набора НЕ ВЫПОЛНЕН — $BAZEL_TEST_REASON; это не приговор набору"
    bazel_test_evidence
    echo "Гейт сидов: ПРОВАЛЕН"
    exit 1 ;;
esac
