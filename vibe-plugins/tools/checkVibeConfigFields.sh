#!/usr/bin/env bash
# Гейт мёртвых полей конфигов: настройка, которую IDE читает и молча игнорирует.
#
# Повод — два случая за один день 08.09.2026, в разных плагинах и написанных с разницей в недели:
# `maxTokens`/`maxSteps` шага пайплайна и `autoStart` записи дев-стека. Оба разбирались из файла
# пользователя, оба были описаны в спеке, оба не делали НИЧЕГО. Тесты этого не видят по построению:
# они проверяют разбор, а разбор как раз работал. Снаружи такая настройка неотличима от рабочей —
# человек пишет ограничение, IDE его читает, не жалуется, и всё идёт как будто ограничения нет.
#
# Проверяется ровно это: свойство, приходящее из JSON пользователя, обязано иметь потребителя
# где-то, кроме объявления и самого разбора. Перекладывание значения (слияние, copy) потребителем
# не считается — оно переносит настройку, а не применяет её.
set -euo pipefail
cd "$(dirname "$0")/../.."
. vibe-plugins/tools/pythonBin.sh

say() { printf '%s\n' "$*"; }

if "$PYTHON" vibe-plugins/tools/checkVibeConfigFields.py; then
  say "Гейт полей конфигов: у каждой настройки из файла есть потребитель"
else
  say "Гейт полей конфигов: ПРОВАЛЕН"
  exit 1
fi
